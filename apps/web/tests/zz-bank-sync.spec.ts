import { expect, test } from '@playwright/test';
import { execFileSync } from 'node:child_process';
import { resolve } from 'node:path';
import { loginAs } from './accounts';

test('bank original synchronizes once, exposes period and actual transactions, and recovers invalid date filters', async ({ page }) => {
  test.setTimeout(90_000);
  const python = resolve('../api/.venv-pg', process.platform === 'win32' ? 'Scripts/python.exe' : 'bin/python');
  const buffer = execFileSync(python, ['-c', "import sys;sys.path[:0]=['../api/src','../api/tests'];from test_bank_statement import xlsx_file;sys.stdout.buffer.write(xlsx_file())"]);
  await loginAs(page, 'treasurer'); await expect(page).toHaveURL(/dashboard/);
  await page.goto('/documents/bank/upload');
  await page.getByLabel('파일 선택').setInputFiles({ name: 'synthetic-bank.xlsx', mimeType: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', buffer });
  await page.getByLabel('문서 제목', { exact: true }).fill('동기화 합성 원본');
  await page.getByRole('button', { name: '문서 저장', exact: true }).click();
  const card = page.getByRole('article').filter({ hasText: '동기화 합성 원본' });
  await expect(card).toContainText('2026-01-01 ~ 2026-01-31 동기화 완료');
  await expect(card).toContainText('신규 2건 · 기존 반영 0건');
  await card.getByRole('link', { name: '새 버전', exact: true }).click();
  await page.getByLabel('파일 선택').setInputFiles({ name: 'synthetic-bank.xlsx', mimeType: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', buffer });
  await page.getByRole('button', { name: '새 버전 저장', exact: true }).click();
  await expect(card).toContainText('신규 0건 · 기존 반영 2건');
  await card.getByRole('button', { name: '버전 이력' }).click();
  await expect(page.getByRole('region', { name: '문서 버전 이력' }).getByText('동기화 완료', { exact: true })).toHaveCount(2);
  await page.screenshot({ path: '../../var/bank-sync-documents.png', fullPage: true });
  await page.goto('/transactions');
  await expect(page.getByText(/카카오뱅크 업로드 자료 · 2건/)).toBeVisible();
  await expect(page.getByTestId('transaction-row')).toHaveCount(2);
  await expect(page.getByText('합성 출금', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: '원본 다운로드' })).toHaveCount(0);
  await expect(page.getByRole('columnheader')).toHaveText(['거래일', '내용', '구분', '금액']);
  await expect(page.getByTestId('transaction-row').first()).not.toContainText('메모');
  await expect(page.getByTestId('transaction-row').first()).not.toContainText('거래 후 잔액');
  await expect(page.getByText('대사 필요', { exact: true })).toHaveCount(0);
  await page.getByLabel('시작일', { exact: true }).fill('2026-02-01');
  await page.getByLabel('종료일', { exact: true }).fill('2026-01-01');
  await expect(page.getByText('시작일은 종료일보다 늦을 수 없습니다.', { exact: true })).toBeVisible();
  await expect(page.getByLabel('시작일', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '전체 기간', exact: true }).click();
  await expect(page.getByTestId('transaction-row')).toHaveCount(2);
  await page.getByRole('combobox', { name: '입출금 구분' }).click();
  await page.getByRole('option', { name: '출금', exact: true }).click();
  await expect(page.getByTestId('transaction-row')).toHaveCount(1);
  for (const width of [1440, 390, 320]) {
    await page.setViewportSize({ width, height: 900 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  }
  await page.screenshot({ path: '../../var/bank-sync-transactions-mobile.png', fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto('/dashboard');
  await expect(page.getByTestId('balance')).toHaveText('1,700원');
  await expect(page.getByTestId('income')).toHaveText('1,000원');
  await expect(page.locator('.data-notice')).toContainText('카카오뱅크 업로드 자료');
  await expect(page.locator('.data-notice')).not.toContainText('개발용 합성 자료');
  await expect(page.locator('[data-widget="summary"]')).toContainText('2026-01 수입과 지출');
  const cashFlow = page.locator('[data-widget="flow"]');
  await expect(cashFlow).toContainText('업로드 자료');
  await expect(cashFlow.locator('.cash-flow-labels > span')).toHaveCount(6);
  await cashFlow.getByRole('button', { name: '주 단위', exact: true }).click();
  await expect(cashFlow.locator('.cash-flow-labels > span')).toHaveCount(8);
  await expect(page.locator('[data-widget="recent"] [data-testid="transaction-row"]')).toHaveCount(2);
  const session = await (await page.request.get('/api/v1/session')).json();
  const updated = execFileSync(python, ['-c', "import sys;sys.path[:0]=['../api/src','../api/tests'];from test_bank_statement import rows,xlsx_file;values=rows();values.append(['','2026.01.08 11:00:00','입금','100','1800','이체','추가 합성 입금','']);sys.stdout.buffer.write(xlsx_file(values))"]);
  const query = new URLSearchParams({ kind: 'bank', title: '대시보드 갱신 원본', filename: 'updated.xlsx', operation_id: crypto.randomUUID() });
  const response = await page.request.post(`/api/v1/families/${session.family_id}/documents?${query}`, { headers: { 'Content-Type': 'application/octet-stream', 'X-CSRF-Token': session.csrf_token, Origin: new URL(page.url()).origin }, data: updated });
  expect(response.ok()).toBeTruthy();
  await page.evaluate(() => window.dispatchEvent(new Event('focus')));
  await expect(page.getByTestId('balance')).toHaveText('1,800원');
  await expect(page.getByTestId('income')).toHaveText('1,100원');
  await expect(page.locator('[data-widget="recent"] [data-testid="transaction-row"]')).toHaveCount(3);
  await page.getByRole('button', { name: '최신 자료 새로고침', exact: true }).click();
  await expect(page.getByTestId('balance')).toHaveText('1,800원');
  await page.screenshot({ path: '../../var/dashboard-bank-desktop.png', fullPage: true });
  await page.emulateMedia({ colorScheme: 'dark' });
  await page.setViewportSize({ width: 390, height: 900 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: '../../var/dashboard-bank-mobile-dark.png', fullPage: true });
});
