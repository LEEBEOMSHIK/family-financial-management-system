import { expect as baseExpect, test } from '@playwright/test';
import { loginAs } from './accounts';
const expect = baseExpect.configure({ timeout: 15_000 });

test('direct widgets auto-save, isolate mobile layouts and reject unauthorized or stale writes', async ({ page, browser }) => {
  test.setTimeout(120_000);
  await loginAs(page, 'member');
  const resize = page.getByRole('button', { name: '수입과 지출 크기 조절', exact: true });
  await expect(resize).toBeVisible();
  await expect(page.getByRole('button', { name: '대시보드 편집', exact: true })).toHaveCount(0);
  const session = await (await page.request.get('/api/v1/session')).json();
  const path = `/api/v1/families/${session.family_id}/dashboard-layout`;
  const headers = { Origin: process.env.E2E_BASE_URL!, 'X-CSRF-Token': session.csrf_token };
  const original = await (await page.request.get(path)).json();
  expect(original.allowed_widgets).not.toContain('tasks');
  expect(original.allowed_widgets).not.toContain('dues');
  expect((await page.request.post(path, { headers, data: { desktop: [...original.desktop, { id: 'dues' }], mobile: original.mobile, revision: original.revision } })).status()).toBe(403);
  const payload = { desktop: original.desktop, mobile: original.mobile, revision: original.revision };
  expect((await page.request.post(path, { headers, data: { ...payload, desktop: [...payload.desktop, { id: 'tasks', width: 'full', height: 'regular', visible: true }] } })).status()).toBe(403);
  expect((await page.request.post(path, { headers, data: { ...payload, desktop: [...payload.desktop, payload.desktop[0]] } })).status()).toBe(422);
  expect((await page.request.post(path, { data: payload, headers: { Origin: process.env.E2E_BASE_URL! } })).status()).toBe(403);
  expect((await page.request.get(path.replace(session.family_id, '00000000-0000-4000-8000-000000000099'))).status()).toBe(404);
  const box = await resize.boundingBox(); if (!box) throw new Error('Missing resize');
  const response = page.waitForResponse(r => r.url().endsWith('/dashboard-layout') && r.request().method() === 'POST');
  await page.mouse.move(box.x + 10, box.y + 10); await page.mouse.down(); await page.mouse.move(box.x + 240, box.y + 160, { steps: 8 }); await page.mouse.up();
  expect((await response).status()).toBe(200);
  await expect(resize).toBeEnabled();
  await expect(page.locator('[data-widget="summary"]')).toHaveAttribute('data-width', 'full');
  expect(await page.locator('[data-widget="summary"]').evaluate(el => el.getBoundingClientRect().height)).toBeGreaterThan(120);
  const handle = page.getByRole('button', { name: '장부 잔액 이동 손잡이', exact: true });
  const from = await handle.boundingBox(); const to = await page.locator('[data-widget="summary"]').boundingBox();
  if (!from || !to) throw new Error('Missing drag boxes');
  const dragged = page.waitForResponse(r => r.url().endsWith('/dashboard-layout') && r.request().method() === 'POST', { timeout: 15000 });
  await page.mouse.move(from.x + 15, from.y + 15); await page.mouse.down(); await page.mouse.move(to.x + 30, to.y + 60, { steps: 5 }); await page.mouse.up();
  expect((await dragged).status()).toBe(200);
  await expect(handle).toBeEnabled();
  // A secondary pointer cannot replace the active gesture; cancellation does not save.
  const revisionBeforeCancel = (await (await page.request.get(path)).json()).revision;
  const cancelBox = await resize.boundingBox(); if (!cancelBox) throw new Error('Missing cancel handle');
  await page.mouse.move(cancelBox.x + 8, cancelBox.y + 8); await page.mouse.down();
  await handle.dispatchEvent('pointerdown', { pointerId: 99, pointerType: 'touch', isPrimary: false, button: 0 });
  await expect(page.locator('[data-widget="summary"]')).toHaveAttribute('data-active', 'true');
  await page.keyboard.press('Escape'); await page.mouse.up();
  expect((await (await page.request.get(path)).json()).revision).toBe(revisionBeforeCancel);
  const stored = await (await page.request.get(path)).json();
  expect(stored.desktop[0].id).toBe('summary');
  await page.reload(); await expect(resize).toBeVisible();
  await expect(page.locator('[data-widget="summary"]')).toHaveAttribute('data-width', 'full');
  expect((await page.request.post(path, { headers, data: payload })).status()).toBe(409);
  await page.setViewportSize({ width: 390, height: 900 });
  await expect(page.locator('[data-widget="summary"]')).toHaveAttribute('data-width', 'half');
  await resize.press('ArrowRight'); await expect(resize).toBeEnabled();
  await page.getByRole('button', { name: '장부 잔액 크기 조절', exact: true }).press('ArrowRight');
  await expect(page.getByRole('status')).toContainText('자동 저장');
  await page.reload(); await expect(resize).toBeVisible();
  await expect(page.locator('[data-widget="balance"]')).toHaveAttribute('data-width', 'full');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await expect(page.locator('[data-widget="balance"]')).toHaveAttribute('data-width', 'half');
  // Lost/failed response keeps the local draft; no blind automatic retry.
  await page.route('**/dashboard-layout', route => route.request().method() === 'POST' ? route.abort() : route.continue());
  await resize.press('ArrowUp'); await expect(page.locator('.dashboard-workspace [role=alert]')).toBeVisible();
  await expect(page.locator('.widget-grid')).toHaveAttribute('aria-busy', 'false');
  await page.unroute('**/dashboard-layout'); await page.getByRole('button', { name: '최신 배치 불러오기' }).click();
  await expect(page.locator('.dashboard-workspace [role=alert]')).toHaveCount(0);
  expect(await page.locator('[data-widget="summary"]').evaluate(el => el.getBoundingClientRect().height)).toBeGreaterThan(120);
  const context = await browser.newContext({ baseURL: process.env.E2E_BASE_URL });
  try {
    const admin = await context.newPage(); await loginAs(admin, 'treasurer');
    await expect(admin.locator('[data-widget="tasks"]')).toHaveCount(1);
    await expect(admin.locator('[data-widget="dues"]')).toHaveCount(1);
    await expect(admin.locator('[data-widget="tasks"] .dues-dashboard')).toHaveCount(0);
    const duesResize=admin.getByRole('button',{name:'회비 미납 현황 크기 조절',exact:true});
    const savedDues=admin.waitForResponse(r=>r.url().endsWith('/dashboard-layout') && r.request().method()==='POST');
    await duesResize.press('ArrowLeft');
    expect((await savedDues).status()).toBe(200);
    await admin.reload();
    await expect(admin.locator('[data-widget="dues"]')).toHaveAttribute('data-width','half');
    await expect(admin.getByRole('button',{name:'회비 미납 현황 이동 손잡이',exact:true})).toBeVisible();
    await expect(admin.getByRole('heading', { name: '내 할 일', exact: true })).toBeVisible();
    await expect(admin.getByRole('region', { name: '승인 대기', exact: true })).toBeVisible();
    await expect(admin.getByRole('region', { name: '송금 대기', exact: true })).toBeVisible();
    await expect(admin.locator('[data-widget="approval"], [data-widget="payment"]')).toHaveCount(0);
    await admin.screenshot({ path: '../../var/expense-demo/direct-widgets-desktop.png', fullPage: true });
    await admin.setViewportSize({ width: 390, height: 900 });
    await admin.screenshot({ path: '../../var/expense-demo/direct-widgets-mobile.png', fullPage: true });
  } finally { await context.close(); }
});
