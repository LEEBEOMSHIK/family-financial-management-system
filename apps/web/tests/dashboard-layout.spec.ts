import { expect as baseExpect, test } from '@playwright/test';
import { loginAs } from './accounts';
const expect = baseExpect.configure({ timeout: 15_000 });

test('personal widgets persist per account, validate permissions and reject stale saves', async ({ page, browser }) => {
  test.setTimeout(90_000);
  await loginAs(page, 'member');
  await expect(page.getByRole('button', { name: '대시보드 편집', exact: true })).toBeVisible();
  const session = await (await page.request.get('/api/v1/session')).json();
  const path = `/api/v1/families/${session.family_id}/dashboard-layout`;
  const headers = { Origin: process.env.E2E_BASE_URL!, 'X-CSRF-Token': session.csrf_token };
  const original = await (await page.request.get(path)).json();
  expect(original.allowed_widgets).not.toContain('approval');
  expect(original.allowed_widgets).not.toContain('payment');
  const payload = { desktop: original.desktop, mobile: original.mobile, revision: original.revision };
  expect((await page.request.post(path, { headers, data: { ...payload, desktop: [...payload.desktop, { id: 'approval', width: 'full', height: 'regular', visible: true }] } })).status()).toBe(403);
  expect((await page.request.post(path, { headers, data: { ...payload, desktop: [...payload.desktop, payload.desktop[0]] } })).status()).toBe(422);
  expect((await page.request.post(path, { data: payload, headers: { Origin: process.env.E2E_BASE_URL! } })).status()).toBe(403);
  expect((await page.request.get(path.replace(session.family_id, '00000000-0000-4000-8000-000000000099'))).status()).toBe(404);
  await page.getByRole('button', { name: '대시보드 편집', exact: true }).click();
  await expect(page.getByRole('combobox', { name: '조회 기간', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: '장부 잔액 숨기기', exact: true }).click();
  await page.getByRole('button', { name: '최근 입출금 앞으로 이동', exact: true }).click();
  await page.getByRole('combobox', { name: '자금 흐름 너비', exact: true }).click();
  await page.getByRole('option', { name: '반폭', exact: true }).click();
  const handle = page.getByRole('button', { name: '수입과 지출 크기 조절', exact: true });
  const box = await handle.boundingBox();
  if (!box) throw new Error('Resize handle missing');
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await page.mouse.down(); await page.mouse.move(box.x + 110, box.y + 140, { steps: 5 }); await page.mouse.up();
  await expect(page.locator('[data-widget="summary"]')).toHaveAttribute('data-width', 'full');
  await expect(page.locator('[data-widget="summary"]')).toHaveAttribute('data-height', 'regular');
  await page.getByRole('button', { name: '지출 분류 이동 손잡이', exact: true }).dragTo(page.locator('[data-widget="flow"]'));
  await page.getByRole('button', { name: '배치 저장', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('배치를 저장했습니다');
  await page.reload();
  await expect(page.locator('[data-widget="balance"]')).toHaveCount(0);
  await expect(page.locator('[data-widget="flow"]')).toHaveAttribute('data-width', 'half');
  const stored = await (await page.request.get(path)).json();
  expect(stored.desktop.find((x: {id: string}) => x.id === 'balance').visible).toBe(false);
  expect(stored.mobile.find((x: {id: string}) => x.id === 'balance').visible).toBe(true);
  expect((await page.request.post(path, { headers, data: payload })).status()).toBe(409);
  const other = await browser.newContext({ baseURL: process.env.E2E_BASE_URL });
  try {
    const admin = await other.newPage(); await loginAs(admin, 'member');
    await expect(admin.locator('[data-widget="balance"]')).toHaveCount(0);
    await expect(admin.locator('[data-widget="flow"]')).toBeVisible();
    await admin.getByRole('button', { name: '로그아웃', exact: true }).click();
    await loginAs(admin, 'super_admin');
    await expect(admin.locator('[data-widget="balance"]')).toBeVisible();
    await expect(admin.locator('[data-widget="approval"]')).toBeVisible();
    await expect(admin.locator('[data-widget="payment"]')).toHaveCount(0);
  } finally { await other.close(); }
  await page.setViewportSize({ width: 390, height: 900 });
  await expect(page.locator('[data-widget="balance"]')).toBeVisible();
  await page.getByRole('button', { name: '대시보드 편집', exact: true }).click();
  await expect(page.getByRole('combobox', { name: '편집할 화면' })).toContainText('모바일 배치');
  await page.getByRole('button', { name: '장부 잔액 숨기기', exact: true }).click();
  await page.getByRole('button', { name: '취소', exact: true }).click();
  await expect(page.locator('[data-widget="balance"]')).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole('button', { name: '대시보드 편집', exact: true }).click();
  await page.getByRole('button', { name: '수입과 지출 숨기기', exact: true }).click();
  await page.getByRole('button', { name: '배치 저장', exact: true }).click();
  await expect(page.getByRole('button', { name: '대시보드 편집', exact: true })).toBeVisible();
  await page.reload();
  await expect(page.locator('[data-widget="summary"]')).toHaveCount(0);
  await expect(page.locator('[data-widget="balance"]')).toBeVisible();
  await page.getByRole('combobox', { name: '화면 모드' }).click();
  await page.getByRole('option', { name: '다크', exact: true }).click();
  await page.screenshot({ path: '../../var/expense-demo/dashboard-widgets-dark-mobile.png', fullPage: true });
  await page.getByRole('combobox', { name: '화면 모드' }).click();
  await page.getByRole('option', { name: '라이트', exact: true }).click();
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole('button', { name: '대시보드 편집', exact: true }).click();
  await page.getByRole('button', { name: '현재 화면 기본 배치로 복원' }).click();
  await page.getByRole('button', { name: '배치 저장', exact: true }).click();
  await expect(page.locator('[data-widget="balance"]')).toBeVisible();
  await expect(page.getByRole('button', { name: '대시보드 편집', exact: true })).toBeVisible();
  await page.screenshot({ path: '../../var/expense-demo/dashboard-widgets.png', fullPage: true });
});
