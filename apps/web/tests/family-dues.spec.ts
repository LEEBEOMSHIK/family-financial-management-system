import { expect, test } from '@playwright/test';
import { account, loginAs } from './accounts';
import { execFileSync } from 'node:child_process';
import { resolve } from 'node:path';

test('administrator configures individual dues and managers see dashboard outstanding', async ({ page }) => {
  test.setTimeout(90000);
  await loginAs(page,'super_admin'); await expect(page).toHaveURL(/dashboard/, {timeout:15000});
  await page.getByRole('link',{name:'가족 관리',exact:true}).click();
  await expect(page.getByRole('heading',{name:'가족 관리',exact:true})).toBeVisible();
  await expect(page.getByText('마감일 미설정',{exact:true})).toBeVisible();
  await expect(page.getByRole('columnheader',{name:'납부일',exact:true})).toBeVisible();
  await expect(page.locator('.dues-table tbody tr').first().locator('[data-label="납부일"]')).toHaveText('미설정');
  await expect(page.getByRole('heading',{name:'회비 납부 확인',exact:true})).toHaveCount(0);
  await expect(page.getByRole('button',{name:'입금 확인',exact:true})).toHaveCount(0);
  const blockedRequest=page.getByRole('button',{name:'납부 요청',exact:true}).first();
  await expect(blockedRequest).toBeDisabled();
  await blockedRequest.hover();
  await expect(page.getByRole('tooltip')).toContainText('조회 월에 적용되는 회비가 없습니다');
  await blockedRequest.focus();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('tooltip')).toHaveCount(0);
  await blockedRequest.blur();
  await blockedRequest.focus();
  await expect(page.getByRole('tooltip')).toBeVisible();
  await page.keyboard.press('Enter');
  await expect(page.getByRole('status')).toHaveCount(0);
  const initialSession=await (await page.request.get('/api/v1/session')).json();
  const initial=await (await page.request.get(`/api/v1/families/${initialSession.family_id}/dues`)).json();
  const currentMonth=initial.today.slice(0,7);
  const chosenDay=new Date(Number(currentMonth.slice(0,4)),Number(currentMonth.slice(5,7)),0).getDate();
  const selectedDeadline=`${currentMonth}-${String(chosenDay).padStart(2,'0')}`;
  await expect(page.getByLabel('공통 납부마감일',{exact:true})).toHaveAttribute('type','date');
  await page.getByLabel('공통 납부마감일',{exact:true}).fill(selectedDeadline);
  await page.getByRole('button',{name:'마감일 저장',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('저장했습니다');
  // Preserve pre-existing monthly fees while scheduling a new fee from next month.
  const session=await (await page.request.get('/api/v1/session')).json();
  const base=`/api/v1/families/${session.family_id}/dues`;
  const overview=await (await page.request.get(base)).json();
  for(const [profile,amount] of [['member','20000'],['treasurer','40000']] as const){
    const seeded=await page.request.post(base,{headers:{'X-CSRF-Token':session.csrf_token,Origin:new URL(page.url()).origin},data:{kind:'fee',month:overview.month,member_id:account(profile).id,amount_krw:amount,operation_id:crypto.randomUUID()}});
    expect(seeded.status()).toBe(200);
  }
  await page.reload();
  await expect(page.locator('.dues-table tbody tr').first().locator('[data-label="납부일"]')).toHaveText(overview.due_on);
  await expect(page.getByRole('heading',{name:'공통 납부마감일 설정',exact:true})).toBeVisible();
  await expect(page.getByLabel('월 회비 (원)',{exact:true})).toHaveCount(0);
  await page.locator('.dues-table tbody tr').filter({hasText:'테스트 구성원'}).getByRole('link',{name:'정보 수정',exact:true}).click();
  await expect(page.getByLabel('월 회비 (원)',{exact:true})).toHaveValue('20000');
  await page.getByLabel('월 회비 (원)',{exact:true}).fill('30000');
  await page.getByRole('button',{name:'변경사항 저장',exact:true}).click();
  const row=page.locator('.dues-table tbody tr').filter({hasText:'테스트 구성원'});
  await expect(row).toContainText('30,000원');
  await expect(row).toContainText('자료 확인 필요');
  await page.locator('.dues-table tbody tr').filter({hasText:'테스트 총무'}).getByRole('link',{name:'정보 수정',exact:true}).click();
  await expect(page.getByLabel('월 회비 (원)',{exact:true})).toHaveValue('40000');
  await page.getByLabel('월 회비 (원)',{exact:true}).fill('50000');
  await page.getByRole('button',{name:'변경사항 저장',exact:true}).click();
  await expect(page.locator('.dues-table tbody tr').filter({hasText:'테스트 총무'})).toContainText('50,000원');
  await row.getByRole('button',{name:'납부 요청',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('외부 알림은 발송되지 않았습니다');
  await page.screenshot({path:'../../var/family-dues-desktop.png',fullPage:true});
  for(const width of [390,320]) {
    await page.setViewportSize({width,height:900});
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
    await expect(row.locator('[data-label="월 회비"]')).toBeVisible();
    await expect(row.locator('[data-label="납부일"]')).toHaveText(overview.due_on);
  }
  await page.emulateMedia({colorScheme:'dark'});
  await page.screenshot({path:'../../var/family-dues-mobile.png',fullPage:true});
  await page.setViewportSize({width:1440,height:1000});
  const python=resolve('../api/.venv-pg',process.platform==='win32'?'Scripts/python.exe':'bin/python');
  const buffer=execFileSync(python,['-c',"import sys;sys.path[:0]=['../api/src','../api/tests'];from test_bank_statement import csv_file;sys.stdout.buffer.write(csv_file())"]);
  await page.goto('/documents/bank/upload');
  await page.getByLabel('파일 선택').setInputFiles({name:'synthetic-dues.csv',mimeType:'text/csv',buffer});
  await page.getByLabel('문서 제목',{exact:true}).fill('회비 확인 합성 자료');
  await page.getByRole('button',{name:'문서 저장',exact:true}).click();
  await expect(page.getByRole('article').filter({hasText:'회비 확인 합성 자료'})).toContainText('동기화 완료');
  await page.goto('/family');
  // Existing confirmed records remain visible; there is no new manual payment UI.
  const deposits=await (await page.request.get(base)).json();
  expect(deposits.deposits.length).toBeGreaterThan(0);
  const confirmed=await page.request.post(base,{headers:{'X-CSRF-Token':session.csrf_token,Origin:new URL(page.url()).origin},data:{kind:'payment',month:overview.month,member_id:account('member').id,transaction_id:deposits.deposits[0].id,operation_id:crypto.randomUUID()}});
  expect(confirmed.status()).toBe(200);
  await page.reload();
  await expect(page.getByRole('button',{name:'납부 확인 저장',exact:true})).toHaveCount(0);
  await expect(row).toContainText('19,000원');
  await page.getByRole('button',{name:'연결 취소',exact:true}).click();
  await expect(row).toContainText('30,000원');
  await expect(page.getByText('입금 확인 · 취소됨',{exact:true})).toBeVisible();
  await loginAs(page,'treasurer'); await expect(page).toHaveURL(/dashboard/, {timeout:15000});
  const summary=page.locator('[data-widget="dues"]');
  await expect(page.locator('[data-widget="tasks"]').getByRole('region',{name:'당월 회비 미납 현황'})).toHaveCount(0);
  await expect(summary).toContainText('남은 납부 2명',{timeout:15000});
  await expect(summary).toContainText('60,000원');
  await expect(summary.getByRole('progressbar')).toHaveAttribute('value','0');
  await expect(summary.getByRole('progressbar')).toHaveAttribute('max','2');
  await expect(summary.getByRole('list',{name:'납부 미확인 구성원'}).getByRole('listitem')).toHaveCount(2);
  await expect(summary.getByRole('heading',{name:'당월 회비 미납 현황'})).toBeVisible();
  await page.getByRole('button',{name:'회비 미납 현황 내용에 맞추기',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('자동 저장');
  await summary.screenshot({path:'../../var/dues-widget-dark.png'});
  await page.setViewportSize({width:320,height:900});
  await page.getByRole('button',{name:'회비 미납 현황 내용에 맞추기',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('자동 저장');
  expect(await summary.evaluate(el=>el.scrollWidth<=el.clientWidth)).toBe(true);
  await summary.screenshot({path:'../../var/dues-widget-mobile.png'});
  await page.setViewportSize({width:1440,height:1000});
  await page.emulateMedia({colorScheme:'light'});
  await summary.screenshot({path:'../../var/dues-widget-light.png'});
  await page.screenshot({path:'../../var/family-dues-dashboard.png',fullPage:true});
  await page.goto('/family');
  await expect(page.getByRole('heading',{name:'구성원별 납부 현황'})).toBeVisible();
  await expect(page.getByRole('heading',{name:'공통 납부마감일 설정'})).toHaveCount(0);
  await page.getByLabel('구성원 검색',{exact:true}).fill('없는구성원');
  await expect(page.getByText('해당 구성원이 없습니다.')).toBeVisible();
  await loginAs(page,'member'); await expect(page).toHaveURL(/dashboard/, {timeout:15000});
  await expect(page.getByRole('region',{name:'당월 회비 미납 현황'})).toHaveCount(0);
  await page.goto('/family');
  await expect(page.getByRole('heading',{name:'접근 권한이 없습니다'})).toBeVisible();
});
