import { expect, test } from '@playwright/test';
import { loginAs } from './accounts';

test('profile registration includes lunar birthday and administrator fee, with treasurer profile editing', async ({page})=>{
  test.setTimeout(90000);
  await loginAs(page,'super_admin');await expect(page).toHaveURL(/dashboard/,{timeout:15000});
  await page.goto('/family/register');
  await page.getByLabel('구성원 이름',{exact:true}).fill('합성 프로필 가족');
  await page.getByLabel('생일 구분',{exact:true}).selectOption('lunar');
  await page.getByRole('button',{name:'생일 달력 열기',exact:true}).click();
  await page.getByLabel('달력 연도',{exact:true}).fill('2000');
  await page.getByLabel('달력 월',{exact:true}).selectOption('4');
  await page.getByRole('button',{name:'4월 30일',exact:true}).click();
  const start=await page.getByLabel('회비 시작일',{exact:true}).inputValue();
  const [y,m]=start.split('-').map(Number);
  const firstMonth=`${y+(m===12?1:0)}-${String(m===12?1:m+1).padStart(2,'0')}`;
  await expect(page.getByText(`첫 회비는 ${firstMonth}부터 전액 적용됩니다. 시작한 달에는 부과하지 않습니다.`)).toBeVisible();
  await page.getByLabel('윤달 생일',{exact:true}).check();
  await page.getByLabel('월 회비 (원)',{exact:true}).fill('35000');
  for(const width of [1440,320]){
    await page.setViewportSize({width,height:1000});
    await page.evaluate(()=>document.documentElement.dataset.theme='dark');
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
    await expect(page.locator('form .fl-card')).toHaveCount(0);
    await page.screenshot({path:`../../var/profile-form-${width}.png`,fullPage:true});
    await page.getByRole('button',{name:'생일 달력 열기',exact:true}).click();
    await expect(page.getByRole('dialog',{name:'생일 달력'})).toBeVisible();
    const box=await page.getByRole('dialog').boundingBox();expect(box && box.x>=0 && box.x+box.width<=width).toBeTruthy();
    await page.screenshot({path:`../../var/birthday-calendar-${width}.png`,fullPage:true});
    await page.getByLabel('달력 연도',{exact:true}).fill('9999');
    await expect(page.getByRole('button',{name:'4월 30일',exact:true})).toBeDisabled();
    await page.keyboard.press('Escape');
    expect(await page.locator('form').evaluate(el=>(el as HTMLFormElement).checkValidity())).toBe(true);
    await expect(page.getByRole('button',{name:'생일 달력 열기',exact:true})).toBeFocused();
  }
  await page.getByRole('button',{name:'구성원 등록',exact:true}).click();
  await expect(page).toHaveURL(/\/family$/);
  const row=page.locator('.dues-table tbody tr').filter({hasText:'합성 프로필 가족'});
  await expect(row).toContainText('음력 2000년 윤달 4월 30일');
  await expect(row).toContainText('35,000');
  await expect(row).toContainText('적용 예정');
  await expect(row).toContainText(`${y}년 ${y-2000}번째 생일`);
  await expect(row).toContainText(firstMonth);
  await page.setViewportSize({width:1440,height:1000});
  await expect(page.getByLabel('회비 시작일',{exact:true})).toHaveCount(0);
  await row.getByRole('link',{name:'정보 수정',exact:true}).click();
  await expect(page.getByLabel('월 회비 (원)',{exact:true})).toHaveValue('35000');
  await expect(page.getByLabel('회비 시작일',{exact:true})).toHaveValue(start);
  const session=await (await page.request.get('/api/v1/session')).json();
  const dues=`/api/v1/families/${session.family_id}/dues`;
  const before=await (await page.request.get(dues)).json();
  await page.getByRole('button',{name:'변경사항 저장',exact:true}).click();
  await expect(page).toHaveURL(/\/family$/);
  const after=await (await page.request.get(dues)).json();
  expect(after.events.filter((e:{kind:string})=>e.kind==='fee').length).toBe(before.events.filter((e:{kind:string})=>e.kind==='fee').length);
  await row.getByRole('link',{name:'정보 수정',exact:true}).click();
  await page.getByLabel('월 회비 (원)',{exact:true}).fill('45000');
  await page.getByRole('button',{name:'변경사항 저장',exact:true}).click();
  await expect(row).toContainText('45,000');
  await loginAs(page,'treasurer');await expect(page).toHaveURL(/dashboard/,{timeout:15000});
  await page.goto('/family');
  await row.getByRole('link',{name:'정보 수정',exact:true}).click();
  await expect(page.getByLabel('월 회비 (원)',{exact:true})).toHaveCount(0);
  await expect(page.getByLabel('생일 구분',{exact:true})).toHaveValue('lunar');
  await page.getByLabel('생일 구분',{exact:true}).selectOption('solar');
  await page.getByRole('button',{name:'생일 달력 열기',exact:true}).click();
  await expect(page.getByLabel('달력 연도',{exact:true})).toHaveValue('2000');
  await page.getByLabel('달력 월',{exact:true}).selectOption('2');
  await page.getByLabel('달력 연도',{exact:true}).fill('1999');
  await expect(page.getByRole('button',{name:'2월 29일',exact:true})).toHaveCount(0);
  await page.getByLabel('달력 연도',{exact:true}).fill('2000');
  await page.getByRole('button',{name:'2월 28일',exact:true}).focus();
  await page.keyboard.press('ArrowRight');
  await expect(page.getByRole('button',{name:'2월 29일',exact:true})).toBeFocused();
  await page.keyboard.press('Enter');
  await expect(page.getByLabel('윤달 생일',{exact:true})).toHaveCount(0);
  await page.getByRole('button',{name:'변경사항 저장',exact:true}).click();
  await expect(page).toHaveURL(/\/family$/);
  await expect(row).toContainText('양력 2000년 2월 29일');await expect(row).toContainText('45,000');
  await page.goto('/family/register');
  await expect(page.getByLabel('월 회비 (원)',{exact:true})).toHaveCount(0);
  await expect(page.getByText('월 회비와 시작일은 총괄관리자가 설정합니다.')).toBeVisible();
});
